#!/bin/sh
# build/build-contents.sh — the generated half of docs/reference/build-contents.md
# (ffmpeg-wasi#70): the FFmpeg version and every component each build enables.
#
#   sh build/build-contents.sh           rewrite the generated block in place
#   sh build/build-contents.sh --check   fail if the committed block is stale
#
# Generated from build/enable-lists.sh, the allowlist libav.sh configures with
# and the capability-conformance suite asserts each built artefact against, so
# the page cannot claim a component no build enables. One column per (profile,
# variant) covers the WASM and native artefacts alike, which holds only while
# TARGET does not change the lists; the script fails if it starts to.
# The backticks in printf formats below are Markdown code spans, not expansions.
# shellcheck disable=SC2016
set -eu

HERE="$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)"
PAGE="$HERE/docs/reference/build-contents.md"
BEGIN='<!-- BEGIN GENERATED by build/build-contents.sh: edit that, not this block -->'
END='<!-- END GENERATED -->'

BUILDS="lean/lgpl lean/gpl intermediate/lgpl intermediate/gpl full/lgpl full/gpl"

claims() { # profile variant
  TARGET=native PROFILE="$1" VARIANT="$2" PRINT_COMPONENT_FLAGS=1 sh "$HERE/build/enable-lists.sh"
}

# components KIND FLAGS: one name per line, from every --enable-KIND= list.
components() {
  printf '%s\n' "$2" | tr ' ' '\n' | sed -n "s/^--enable-$1=//p" | tr ',' '\n' | grep -v '^$' || true
}

table() { # kind heading
  printf '\n### %s\n\n' "$2"
  printf '| %s |' "$1"
  for b in $BUILDS; do printf ' %s |' "$b"; done
  printf '\n|---|'
  for _ in $BUILDS; do printf -- '---|'; done
  printf '\n'

  tmp_all="$WORK/$1.all"
  : >"$tmp_all"
  for b in $BUILDS; do
    components "$1" "$(cat "$WORK/${b%/*}-${b#*/}")" | sort -u >"$WORK/$1.${b%/*}-${b#*/}"
    # Upstream builds these only under --enable-gpl, whatever the allowlist asks.
    # busybox grep drops every line given an empty pattern file, hence the -s.
    if [ "${b#*/}" = lgpl ] && [ -s "$WORK/gpl-only.$1" ]; then
      grep -vxF -f "$WORK/gpl-only.$1" "$WORK/$1.${b%/*}-${b#*/}" >"$WORK/kept" || true
      mv "$WORK/kept" "$WORK/$1.${b%/*}-${b#*/}"
    fi
    cat "$WORK/$1.${b%/*}-${b#*/}" >>"$tmp_all"
  done

  sort -u "$tmp_all" | while IFS= read -r name; do
    printf '| `%s` |' "$name"
    for b in $BUILDS; do
      if grep -qx -- "$name" "$WORK/$1.${b%/*}-${b#*/}"; then printf ' yes |'; else printf '  |'; fi
    done
    printf '\n'
  done
}

generate() {
  version="$(sh "$HERE/build/ffmpeg-version.sh")"
  printf '%s\n\n' "$BEGIN"
  printf 'Every build is FFmpeg **%s**, from `build/ffmpeg-version.txt`.\n' "$version"
  printf 'The `full` profile is built only as a native driver; the others are built as both.\n'
  gated="$(printf '%s\n' "$gpl_only" | tr ' ' '\n' | sed 's/^[^=]*=//' | grep -v '^$' | sort | sed 's/.*/`&`/' | paste -sd, - | sed 's/,/, /g')"
  if [ -n "$gated" ]; then
    printf '\nThe allowlist names %s, but upstream builds them only under\n' "$gated"
    printf '`--enable-gpl`, so they are blank in the `lgpl` columns.\n'
  fi
  table decoder Decoders
  table encoder Encoders
  table demuxer Demuxers
  table muxer Muxers
  table filter Filters
  table bsf 'Bitstream filters'
  table protocol Protocols
  printf '\n%s\n' "$END"
}

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

gpl_only="$(TARGET=native PRINT_GPL_ONLY_COMPONENTS=1 sh "$HERE/build/enable-lists.sh")"
for kind in decoder encoder demuxer muxer filter bsf protocol; do
  printf '%s\n' "$gpl_only" | tr ' ' '\n' | sed -n "s/^$kind=//p" >"$WORK/gpl-only.$kind"
done
for b in $BUILDS; do
  claims "${b%/*}" "${b#*/}" >"$WORK/${b%/*}-${b#*/}"
  case "$b" in full/*) continue ;; esac
  TARGET=wasm PROFILE="${b%/*}" VARIANT="${b#*/}" PRINT_COMPONENT_FLAGS=1 \
    sh "$HERE/build/enable-lists.sh" >"$WORK/wasm"
  cmp -s "$WORK/wasm" "$WORK/${b%/*}-${b#*/}" || {
    echo "build-contents: $b enables different components for wasm and native;" >&2
    echo "  the page's one column per build no longer covers both" >&2
    exit 1
  }
done

generate >"$WORK/block"

[ -f "$PAGE" ] || { echo "build-contents: no page at $PAGE" >&2; exit 2; }
if ! grep -qxF "$BEGIN" "$PAGE" || ! grep -qxF "$END" "$PAGE"; then
  echo "build-contents: $PAGE has lost its generated-block markers" >&2
  exit 2
fi

# Everything before BEGIN, the fresh block, everything after END.
awk -v begin="$BEGIN" -v end="$END" -v block="$WORK/block" '
  $0 == begin { while ((getline line < block) > 0) print line; skip = 1; next }
  $0 == end   { skip = 0; next }
  !skip       { print }
' "$PAGE" >"$WORK/page"

if [ "${1:-}" = --check ]; then
  if ! cmp -s "$PAGE" "$WORK/page"; then
    echo "build-contents: docs/reference/build-contents.md is stale; run sh build/build-contents.sh" >&2
    diff -u "$PAGE" "$WORK/page" >&2 || true
    exit 1
  fi
  exit 0
fi

cat "$WORK/page" >"$PAGE"
